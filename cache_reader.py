"""
cache_reader.py — Read-side adapter over the rolling options cache.

The cache (data/cache/rolling_options/<INDEX>/) stores one JSON per
(period, expiry-level, strike-offset, side).  Each file holds minute-level
parallel arrays: iv, oi, strike, spot, close, timestamp (epoch seconds, IST
trading hours).  CALL files populate data["ce"], PUT files data["pe"].

Expiry levels map onto the pyramid as:
    WEEK_E1 → current expiry, WEEK_E2 → next, WEEK_E3 → far.

This cache is not fetched or generated by this project — it's raw historical
options-chain data populated separately (see README's Data section).
"""

from __future__ import annotations

import json
import re
from bisect import bisect_right
from dataclasses import dataclass
from datetime import date, datetime, timedelta, timezone
from functools import lru_cache
from pathlib import Path
from typing import Dict, List, Optional, Tuple

CACHE_DIR = Path(__file__).parent / "data" / "cache" / "rolling_options"

IST = timezone(timedelta(hours=5, minutes=30))

# Pyramid tier → cache expiry-level token.
EXPIRY_LEVELS: Dict[str, str] = {
    "current": "WEEK_E1",
    "next":    "WEEK_E2",
    "far":     "WEEK_E3",
}

MAX_STRIKE_OFFSET = 10  # scan ATM±10; cache may hold fewer (2025 has ±3)

# Nearest-bar tolerance when snapping a target time onto the minute grid.
_SNAP_TOLERANCE_SEC = 45 * 60

_FNAME_PAT = re.compile(
    r"^(\d{4}-\d{2}-\d{2})_(\d{4}-\d{2}-\d{2})_"
    r"(WEEK|MONTH)_(E[123])_(ATM(?:[+-]\d+)?)_(CALL|PUT)\.json$"
)


def strike_label(offset: int) -> str:
    if offset == 0:
        return "ATM"
    return f"ATM{offset:+d}"


# ─── File index ──────────────────────────────────────────────────────────────

@lru_cache(maxsize=4)
def _file_index(index: str) -> Dict[Tuple[str, str, str], List[Tuple[str, str, Path]]]:
    """
    One directory scan per index. Maps (level, strike_label, side) →
    sorted list of (from_date, to_date, path) period files.
    """
    out: Dict[Tuple[str, str, str], List[Tuple[str, str, Path]]] = {}
    index_dir = CACHE_DIR / index
    if not index_dir.is_dir():
        return out
    for fp in index_dir.iterdir():
        m = _FNAME_PAT.match(fp.name)
        if not m or m.group(3) != "WEEK":
            continue
        key = (f"WEEK_{m.group(4)}", m.group(5), m.group(6))
        out.setdefault(key, []).append((m.group(1), m.group(2), fp))
    for lst in out.values():
        lst.sort()
    return out


def find_file(index: str, d: date, level: str, offset: int, side: str) -> Optional[Path]:
    """Locate the period file covering date `d`, widest coverage wins."""
    d_str = d.strftime("%Y-%m-%d")
    candidates = [
        (to_d, fp)
        for from_d, to_d, fp in _file_index(index).get(
            (level, strike_label(offset), side), []
        )
        if from_d <= d_str <= to_d
    ]
    if not candidates:
        return None
    return max(candidates)[1]


# ─── Series loading ──────────────────────────────────────────────────────────

@lru_cache(maxsize=256)
def _load_series(path_str: str, side: str) -> Optional[dict]:
    with open(path_str) as f:
        payload = json.load(f)
    leg = payload.get("data", {}).get("ce" if side == "CALL" else "pe")
    if not leg or not leg.get("timestamp"):
        return None
    return leg


@dataclass(frozen=True)
class Bar:
    """One minute bar for a single option contract."""
    ts: int
    strike: float
    spot: float
    oi: float
    iv: float          # percent, as stored (e.g. 21.78)
    premium: float     # option close


def read_bar(
    index: str, d: date, hhmm: str, level: str, offset: int, side: str
) -> Optional[Bar]:
    """
    Value of one contract at (or at the latest bar before) `hhmm` IST on `d`.
    Returns None when the strike/level has no file or no bar on that date.
    """
    fp = find_file(index, d, level, offset, side)
    if fp is None:
        return None
    leg = _load_series(str(fp), side)
    if leg is None:
        return None

    target = int(
        datetime(d.year, d.month, d.day, int(hhmm[:2]), int(hhmm[2:]), tzinfo=IST)
        .timestamp()
    )
    ts_arr = leg["timestamp"]
    i = bisect_right(ts_arr, target) - 1
    if i < 0 or target - ts_arr[i] > _SNAP_TOLERANCE_SEC:
        return None
    bar_day = datetime.fromtimestamp(ts_arr[i], IST).date()
    if bar_day != d:
        return None

    try:
        return Bar(
            ts=ts_arr[i],
            strike=float(leg["strike"][i]),
            spot=float(leg["spot"][i]),
            oi=float(leg["oi"][i]),
            iv=float(leg["iv"][i]),
            premium=float(leg["close"][i]),
        )
    except (IndexError, TypeError, ValueError):
        return None


def spot_series(index: str, d: date) -> Tuple[List[int], List[float]]:
    """Full minute-level (timestamps, spot) for date `d`, from the ATM E1 call."""
    fp = find_file(index, d, "WEEK_E1", 0, "CALL")
    if fp is None:
        return [], []
    leg = _load_series(str(fp), "CALL")
    if leg is None:
        return [], []
    day_start = int(datetime(d.year, d.month, d.day, tzinfo=IST).timestamp())
    day_end = day_start + 86400
    ts_arr = leg["timestamp"]
    lo = bisect_right(ts_arr, day_start)
    hi = bisect_right(ts_arr, day_end)
    return ts_arr[lo:hi], leg["spot"][lo:hi]


def trading_dates(index: str, year: int) -> List[date]:
    """All trading dates for `year` observed in the ATM E1 call timestamps."""
    dates: set = set()
    for from_d, to_d, fp in _file_index(index).get(("WEEK_E1", "ATM", "CALL"), []):
        if to_d < f"{year}-01-01" or from_d > f"{year}-12-31":
            continue
        leg = _load_series(str(fp), "CALL")
        if leg is None:
            continue
        for ts in leg["timestamp"]:
            dt = datetime.fromtimestamp(ts, IST).date()
            if dt.year == year:
                dates.add(dt)
    return sorted(dates)
